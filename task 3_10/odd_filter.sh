#!/bin/bash

# Числовой фильтр: выводит нечетные числа от 1 до 20
# Останавливается при достижении числа 15

echo "Нечетные числа от 1 до 20 (остановка на 15):"
echo "============================================"

# Перебираем числа от 1 до 20
for ((i=1; i<=20; i++))
do
    # Проверяем, не достигли ли мы числа 15
    if [ $i -eq 15 ]; then
        echo "Достигнуто число 15. Остановка."
        break
    fi
    
    # Проверяем, четное ли число
    if [ $((i % 2)) -eq 0 ]; then
        # Если четное - пропускаем вывод
        continue
    fi
    
    # Выводим нечетное число
    echo $i
done

echo "============================================"
