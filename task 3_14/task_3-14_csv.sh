echo "=== Исходные данные из файла data.csv ==="
cat data.csv
echo ""

# 1. Выводим названия товаров (вторая колонка)
echo "=== Названия товаров ==="
awk -F "," '{print $2}' data.csv
echo ""

# 2. Выводим товары дороже 20 (цена в третьей колонке)
echo "=== Товары дороже 20 ==="
awk -F "," '$3 > 20 {print $2 " - " $3 " у.е."}' data.csv
echo ""

# 3. Считаем общую стоимость всех товаров
echo "=== Общая стоимость всех товаров ==="
awk -F "," '{sum += $3} END {print "Сумма: " sum " у.е."}' data.csv
echo ""

# Дополнительно: статистика по товарам
echo "=== Дополнительная статистика ==="
