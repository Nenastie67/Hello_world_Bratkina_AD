echo "=== Анализ использования дискового пространства ==="
echo "Дата и время: $(date)"
echo ""

# Анализируем вывод df -h с помощью awk
df -h | awk '
# Пропускаем заголовок (первую строку)
NR > 1 {
    # Сохраняем название файловой системы (1-й столбец) и процент заполнения (5-й столбец)
    fs_name = $1
    # Удаляем символ % из значения процента
    percent = $5
    gsub(/%/, "", percent)
    
    # Выводим информацию о каждой файловой системе
    printf "Файловая система: %-20s Заполнено: %3s%%", fs_name, $5
    
    # Проверяем, превышает ли заполнение 90%
    if (percent > 90) {
        printf " ⚠️  ВНИМАНИЕ! Критический уровень заполнения!"
    } else if (percent > 80) {
        printf " ⚠️  Предупреждение: высокий уровень заполнения"
    }
    
    printf "\n"
    
    # Для мониторинга: считаем общее количество и критических
    total++
    if (percent > 90) {
        critical++
    }
}

# После обработки всех строк выводим итоговую статистику
END {
    if (total > 0) {
        printf "\n=== Итоговая статистика ===\n"
        printf "Всего файловых систем: %d\n", total
        printf "Из них критических (>90%%): %d\n", critical
        
        # Если есть критические разделы, возвращаем ненулевой код
        if (critical > 0) {
            exit 1
        }
    }
}'

# Альтернативный более простой вариант:
echo ""
echo "=== Упрощенный вариант ==="
df -h | awk 'NR>1 {
    printf "%-20s %s", $1, $5;
    if ($5+0 > 90) print " ⚠️ КРИТИЧНО!";
    else if ($5+0 > 80) print " ⚠️ Внимание";
    else print ""
}'

# Проверяем код возврата
if [ $? -eq 1 ]; then
    echo ""
    echo "❌ Обнаружены критические разделы! Требуется внимание администратора."
else
    echo ""
    echo "✅ Критических разделов не обнаружено."
fi
