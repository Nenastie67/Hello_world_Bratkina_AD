echo "=== Исходные данные из файла students.txt ==="
cat students.txt
echo ""

# 1. Выводим студентов с оценкой выше 80
echo "=== Студенты с оценкой выше 80 ==="
awk '$2 > 80 {print $1 " - " $2 " баллов"}' students.txt
echo ""

# 2. Выводим студентов с оценкой ниже 70
echo "=== Студенты с оценкой ниже 70 ==="
awk '$2 < 70 {print $1 " - " $2 " баллов"}' students.txt
echo ""

# 3. Выводим только первую строку файла
echo "=== Первая строка файла ==="
awk 'NR == 1 {print "Строка " NR ": " $0}' students.txt
