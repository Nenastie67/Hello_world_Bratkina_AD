#!/bin/bash

# Функция для проверки прав суперпользователя
check_root() {
    # $EUID - эффективный ID пользователя
    # -ne - not equal (не равно)
    if [ $EUID -ne 0 ]; then
        echo "=========================================="
        echo "ОШИБКА: Недостаточно прав!"
        echo "=========================================="
        echo "Этот скрипт требует прав суперпользователя."
        echo ""
        echo "Текущий пользователь: $(whoami)"
        echo "Текущий UID: $EUID"
        echo ""
        echo "Для запуска используйте:"
        echo "  sudo $0"
        echo "=========================================="
        
        # Возвращаем код ошибки и завершаем скрипт
        exit 1
    fi
    
    # Если дошли сюда - всё хорошо
    return 0
}

# Основная часть скрипта
echo "Запуск скрипта: $0"
echo "=========================================="

# Вызов функции проверки
check_root

# Если дошли до этой строки - проверка пройдена
echo "✓ Проверка прав пройдена успешно!"
echo "✓ Скрипт запущен от root (UID: $EUID)"
echo "=========================================="

# Демонстрация работы с аргументами функции
echo ""
echo "Демонстрация работы с аргументами:"

# Функция с аргументами
show_message() {
    local msg_type="$1"    # local - локальная переменная
    local msg_text="$2"    # $2 - второй аргумент функции
    local timestamp=$(date +%H:%M:%S)
    
    echo "[$timestamp] [$msg_type]: $msg_text"
}

# Вызов функции с разными аргументами
show_message "INFO" "Скрипт выполняется от root"
show_message "SUCCESS" "Все проверки пройдены"
